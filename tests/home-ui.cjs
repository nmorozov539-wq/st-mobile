// Real Pocket DOM at phone width against the isolated ST 1.19.0 fixture (8123).
const {chromium}=require(process.env.POCKET_PLAYWRIGHT_MODULE||'playwright');
const assert=require('node:assert/strict');const fs=require('node:fs');
const origin=process.env.POCKET_TEST_ORIGIN||'http://127.0.0.1:8123';
const out=process.env.POCKET_UI_OUTPUT||'/tmp/pocket-home-ui';fs.mkdirSync(out,{recursive:true});
let passed=0;const ok=(v,n)=>{assert.ok(v,n);passed++;console.log('PASS '+n);};
(async()=>{
 const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
 const ctx=await browser.newContext({viewport:{width:390,height:844},hasTouch:true,isMobile:true});
 const page=await ctx.newPage();const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(origin+'/st-mobile/');
 await page.waitForFunction(()=>document.querySelector('#status').textContent==='Engine ready',null,{timeout:90000});
 await page.locator('[data-page="home"]').click();
 await page.waitForSelector('.home-page');
 const text=await page.locator('.home-page').innerText();
 ok(/A little place\.\s*A lot of stories\./.test(text)&&/Make yourself at home\./.test(text),'tagline and welcome');
 ok(await page.locator('.home-row:has-text("Engine") .home-state').innerText()==='Connected','engine connected');
 const counts=await page.locator('.home-counts strong').allInnerTexts();
 ok(counts.length===3&&counts.every(v=>/^\d/.test(v)),'three counts shown: '+counts.join(','));
 ok(Number(counts[0])>=1,'characters counted from the real library');
 ok(!(await page.locator('.home-page').innerText()).match(/Stop current reply|Recent conversations/),'no duplicate chat shortcuts');
 ok(await page.locator('#bottom-nav [data-page="home"]').getAttribute('class').then(c=>/current/.test(c||'')),'Home highlighted in nav');
 ok(/0\.\d+\.\d+/.test(await page.locator('.home-foot').innerText()),'version in footer');
 await page.screenshot({path:`${out}/home.png`});
 await page.locator('#app-settings').click();await page.waitForSelector('.sp-page');
 ok(await page.locator('#page-title').textContent()==='Settings','gear opens Settings');
 await page.locator('#page-back').click();await page.waitForSelector('.home-page');
 ok(true,'back returns to Home');
 ok(errors.length===0,'no page errors '+errors.join('|'));
 console.log(`${passed} checks passed`);await browser.close();
})().catch(e=>{console.error(e);process.exit(1);});
