 await page.locator('#page-wi-activation').click();await page.waitForSelector('.wi-slider');
 ok(Number(await box().inputValue())===next,'activation value persisted');
 await box().fill(String(old));await box().blur();
 await page.locator('.wi-save').click();await page.waitForSelector('.wi-page');
 await page.locator('#page-wi-activation').click();await page.waitForSelector('.wi-slider');
