 await shot('library');
 await page.locator(`.wi-book:has-text("${B}") .wi-entry-open`).click();await page.waitForSelector('.wi-editor');
 await page.locator('.wi-editor input').first().fill('Changed');
 await page.getByRole('button',{name:'Cancel'}).click();
 ok(await modal.isVisible(),'dirty cancel asks to discard');
 await modal.getByRole('button',{name:'Discard'}).click();
 await page.waitForSelector('.wi-page');
 ok((await disk(B)).entries[0].comment==='Moss lore','discard leaves disk unchanged');
 await page.locator('#page-wi-activation').click();await page.waitForSelector('.wi-slider');
 await shot('activation');
 const box=()=>page.locator('.wi-slider').nth(0).locator('input[type=number]');
